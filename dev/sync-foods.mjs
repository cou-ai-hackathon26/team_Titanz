// Copies the food ids and names from lib/foods.ts into api/food-list.ts, so the scan API
// and the app always use the SAME food list. Run after changing lib/foods.ts:
//   cd api && npm run sync-foods
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const { FOODS } = await import(path.join(root, 'lib/foods.ts'));

const list = FOODS.map((f) => ({ id: f.id, nameBn: f.nameBn, nameEn: f.nameEn, unit: f.unit, portion: `${f.portion} ${f.portionUnit}` }));
const out = `// GENERATED by dev/sync-foods.mjs from lib/foods.ts. Do not edit by hand.
// The scan AI may only answer with these ids.
export const FOOD_LIST = ${JSON.stringify(list, null, 2)} as const;
`;
writeFileSync(path.join(root, 'api/food-list.ts'), out);
console.log(`Wrote ${list.length} foods to api/food-list.ts`);
